            AppendArgumentTable(builder, "Outputs", operation.Arguments.Where(IsOutput), isInput: false);
        }

        return builder.ToString();
    }

    public static string GenerateCoverageManifest(
        CommandCatalogManifest manifest,
        IReadOnlyList<CommandCatalogOperation> operations)
    {
        var partitions = manifest.ProtocolPartitions.ToDictionary(
            partition => partition.Alias,
            StringComparer.Ordinal);
        var document = new
        {
            schema_version = 1,
            generated_by = CommandCatalogGenerator.GeneratedArtifactIdentity,
            manifest.CatalogId,
            manifest.CatalogRevision,
            manifest.SpatialAnalyzerTarget,
            manifest.TargetProtocolPackage,
            operations = operations.Select(operation => new
            {
                operation.OperationId,
                operation.InventoryKey,
                operation.MpStep,
                protocol_file = partitions[operation.OperationId.Split('.')[0]].ProtoFile,
                service = operation.Protocol.Service,
                rpc = operation.Protocol.Rpc,
                request = operation.Protocol.Request,
                result = operation.Protocol.Result,
                fully_qualified_method =
                    $"/{manifest.TargetProtocolPackage}.{operation.Protocol.Service}/{operation.Protocol.Rpc}",
                effect = operation.Risk.Effect,
                execution_scope = operation.ExecutionScope,
                isolation_review = operation.Documentation.Isolation,
                replay_safety = operation.Risk.ReplaySafety,
                generated = new
                {
                    protocol = true,
                    command_adapter = true,
                    result_adapter = true,
                    documentation = true
                },
                inputs = operation.Arguments.Where(IsInput).OrderBy(argument => argument.Ordinal)
                    .Select(argument => new
                    {
                        argument.ArgumentId,
                        argument.Ordinal,
                        argument.SdkOrder,
                        argument.MpName,
                        argument.Direction,
                        argument.SemanticType,
                        argument.DataClassification,
                        field_number = argument.FieldNumbers.Request,
                        setter = argument.SdkBinding.Setter,
                        presence = argument.Input?.Presence,
                        omission_behavior = argument.Input?.OmissionBehavior,
                        default_status = argument.Input?.Default.Status
                    }),
                outputs = operation.Arguments.Where(IsOutput).OrderBy(argument => argument.Ordinal)
                    .Select(argument => new
                    {
                        argument.ArgumentId,
                        argument.Ordinal,
                        argument.SdkOrder,
                        argument.MpName,
                        argument.Direction,
                        argument.ResultOnly,
                        argument.SemanticType,
                        argument.DataClassification,
                        field_number = argument.FieldNumbers.Result,
                        getter = argument.SdkBinding.Getter
                    })
            })
        };
        return JsonSerializer.Serialize(document, CoverageJsonOptions) + "\n";
    }

    private static void AppendCatalogMetadata(
        StringBuilder builder,
        CommandCatalogManifest manifest,
        IReadOnlyList<CommandCatalogOperation> operations)
    {
        builder.AppendLine();
        builder.AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"Briosa.Generator\", \"1.0\")]");
        builder.AppendLine("internal static class TargetCatalogMetadata");
        builder.AppendLine("{");
        AppendConstant(builder, "CatalogId", manifest.CatalogId);
        AppendConstant(builder, "CatalogRevision", manifest.CatalogRevision);
        AppendConstant(builder, "SpatialAnalyzerTarget", manifest.SpatialAnalyzerTarget);
        AppendConstant(builder, "TargetProtocolPackage", manifest.TargetProtocolPackage);
        builder.AppendLine();
        builder.AppendLine("    public static IReadOnlyList<CatalogOperationDescriptor> Operations { get; } =");
        builder.AppendLine("        [");
        foreach (var operation in operations)
        {
            var service = $"{manifest.TargetProtocolPackage}.{operation.Protocol.Service}";
            builder.Append("            new(\"").Append(EscapeCSharp(operation.OperationId))
                .Append("\", \"").Append(EscapeCSharp(operation.MpStep))
                .Append("\", \"").Append(EscapeCSharp(service))
                .Append("\", \"").Append(EscapeCSharp(operation.Protocol.Rpc))
                .Append("\", \"/").Append(EscapeCSharp(service)).Append('/')
                .Append(EscapeCSharp(operation.Protocol.Rpc))
                .Append("\", \"").Append(EscapeCSharp(operation.Risk.Effect))
                .Append("\", CoreProtocol.OperationExecutionScope.")
                .Append(ToPascalCase(operation.ExecutionScope))
                .Append(", CoreProtocol.ReplaySafety.")
                .Append(ToPascalCase(operation.Risk.ReplaySafety))
                .Append(", [")
                .Append(string.Join(", ", operation.Risk.Flags.Select(flag =>
                    $"\"{EscapeCSharp(flag)}\"")))
                .AppendLine("]),");
        }

        builder.AppendLine("        ];");
        builder.AppendLine("}");
    }

    private static void AppendConstant(StringBuilder builder, string name, string value) =>
        builder.Append("    public const string ").Append(name).Append(" = \"")
            .Append(EscapeCSharp(value)).AppendLine("\";");

    private static void AppendBinding(StringBuilder builder, CommandCatalogOperation operation)
    {
        var inputs = operation.Arguments.Where(IsInput).OrderBy(argument => argument.Ordinal).ToArray();
        var outputs = operation.Arguments.Where(IsOutput).OrderBy(argument => argument.Ordinal).ToArray();
        ValidateBindings(operation, inputs, outputs);

        builder.AppendLine();
        builder.AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"Briosa.Generator\", \"1.0\")]");
        builder.Append("internal static class ").Append(operation.Protocol.Service)
            .Append(operation.Protocol.Rpc).AppendLine("Binding");
        builder.AppendLine("{");
        builder.Append("    public const string OperationId = \"")
            .Append(EscapeCSharp(operation.OperationId)).AppendLine("\";");
        builder.Append("    public const string StepName = \"")
            .Append(EscapeCSharp(operation.MpStep)).AppendLine("\";");

        foreach (var argument in inputs.Concat(outputs).DistinctBy(argument => argument.ArgumentId))
        {
            var name = ToPascalCase(argument.ArgumentId);
            builder.Append("    public const string ").Append(name).Append("ArgumentName = \"")
                .Append(EscapeCSharp(argument.MpName)).AppendLine("\";");
            builder.Append("    public const string ").Append(name).Append("FieldName = \"")
                .Append(EscapeCSharp(argument.ArgumentId)).AppendLine("\";");
            if (IsInput(argument))
            {
                builder.Append("    public const string ").Append(name).Append("Setter = \"")
                    .Append(EscapeCSharp(argument.SdkBinding.Setter!)).AppendLine("\";");
            }

            if (IsOutput(argument))
            {
                builder.Append("    public const string ").Append(name).Append("Getter = \"")
                    .Append(EscapeCSharp(argument.SdkBinding.Getter!)).AppendLine("\";");
            }
        }

        builder.AppendLine();
        AppendOutputContracts(builder, outputs);
        builder.AppendLine();
        AppendCreateCommand(builder, operation, inputs, outputs);
        builder.AppendLine();
        AppendCreateResult(builder, operation, outputs);
        builder.AppendLine("}");
    }

    private static void ValidateBindings(
        CommandCatalogOperation operation,
        IReadOnlyList<CommandCatalogArgument> inputs,
        CommandCatalogArgument[] outputs)
    {
        foreach (var input in inputs)
        {
            if (input.Input is null || input.SdkBinding.Status != "available" ||
                string.IsNullOrWhiteSpace(input.SdkBinding.Setter))
            {
                throw new NotSupportedException(
                    $"Operation '{operation.OperationId}' input '{input.ArgumentId}' is not generation-ready.");
            }

            if (input.Input.OmissionBehavior == "set_catalog_default" &&
                input.Input.Default.Status != "reviewed")
            {
                throw new NotSupportedException(
                    $"Operation '{operation.OperationId}' input '{input.ArgumentId}' may use only a reviewed catalog default.");
            }
        }

        foreach (var output in outputs)
        {
            if (output.SdkBinding.Status != "available" ||
                string.IsNullOrWhiteSpace(output.SdkBinding.Getter))
            {
                throw new NotSupportedException(
                    $"Operation '{operation.OperationId}' output '{output.ArgumentId}' is not generation-ready.");
            }
        }
    }

    private static void AppendOutputContracts(
        StringBuilder builder,
        CommandCatalogArgument[] outputs)
    {
        builder.AppendLine("    public static IReadOnlyList<OperationOutputContract> OutputContracts { get; } =");
        if (outputs.Length == 0)
        {
            builder.AppendLine("        [];");
            return;
        }

        builder.AppendLine("        [");
        foreach (var output in outputs)
        {
            var name = ToPascalCase(output.ArgumentId);
            builder.Append("            new(").Append(name).Append("FieldName, ")
                .Append(name).Append("ArgumentName, WorkerMpValueKind.")
                .Append(ToWorkerValueKind(output.SemanticType)).AppendLine("),");
        }

        builder.AppendLine("        ];");
    }

    private static void AppendCreateCommand(
        StringBuilder builder,
        CommandCatalogOperation operation,
        IReadOnlyList<CommandCatalogArgument> inputs,
        CommandCatalogArgument[] outputs)
    {
        builder.Append("    public static WorkerMpCommand CreateCommand(TargetProtocol.")
            .Append(operation.Protocol.Request).AppendLine(" request)");
        builder.AppendLine("    {");
        builder.AppendLine("        ArgumentNullException.ThrowIfNull(request);");
        builder.AppendLine("        List<WorkerMpInputArgument> inputs = [];");
        foreach (var input in inputs)
        {
            AppendInputMapping(builder, input);
        }

        builder.AppendLine("        return new WorkerMpCommand(");
        builder.AppendLine("            OperationId,");
        builder.AppendLine("            StepName,");
        builder.AppendLine("            InputArguments: inputs,");
        if (outputs.Length == 0)
        {
            builder.AppendLine("            OutputArguments: []);");
        }
        else
        {
            builder.AppendLine("            OutputArguments:");
            builder.AppendLine("            [");
            foreach (var output in outputs)
            {
                var name = ToPascalCase(output.ArgumentId);
                builder.Append("                new(").Append(name).Append("ArgumentName, WorkerMpValueKind.")
                    .Append(ToWorkerValueKind(output.SemanticType)).Append(", ")
                    .Append(name).AppendLine("Getter),");
            }

            builder.AppendLine("            ]);");
        }

        builder.AppendLine("    }");
    }

    private static void AppendInputMapping(StringBuilder builder, CommandCatalogArgument input)
    {
        var property = ToPascalCase(input.ArgumentId);
        var present = IsMessageType(input.SemanticType)
            ? $"request.{property} is not null"
            : $"request.Has{property}";
        builder.Append("        if (").Append(present).AppendLine(")");
        builder.AppendLine("        {");
        if (RequiresComponentValidation(input.SemanticType))
        {
            AppendMessageValidation(builder, input, property, "            ");
        }

        builder.Append("            inputs.Add(").Append(CreateInputExpression(input, $"request.{property}"))
            .AppendLine(");");
        builder.AppendLine("        }");

        if (input.Input!.OmissionBehavior == "set_catalog_default")
        {
            builder.AppendLine("        else");
            builder.AppendLine("        {");
            builder.Append("            inputs.Add(")
                .Append(CreateInputExpression(input, DefaultExpression(input)))
                .AppendLine(");");
            builder.AppendLine("        }");
        }
        else if (input.Input.Presence == "required" ||
                 input.Input.OmissionBehavior == "reject_request")
        {
            builder.AppendLine("        else");
            builder.AppendLine("        {");
            builder.Append("            throw new ArgumentException(\"Required request field '")
                .Append(EscapeCSharp(input.ArgumentId)).AppendLine("' is missing.\", nameof(request));");
            builder.AppendLine("        }");
        }
    }

    private static void AppendMessageValidation(
        StringBuilder builder,
        CommandCatalogArgument input,
        string property,
        string indentation)
    {
        var value = $"request.{property}";
        var condition = input.SemanticType switch
        {
            "transform" => $"{value}.Values.Count != 16",
            "world_transform" =>
                $"{value}.Transform is null || {value}.Transform.Values.Count != 16 || !{value}.HasScaleFactor",
            "rgb_color" =>
                $"!{value}.HasRed || {value}.Red > byte.MaxValue || !{value}.HasGreen || {value}.Green > byte.MaxValue || !{value}.HasBlue || {value}.Blue > byte.MaxValue",
            "file_reference" => $"!{value}.HasPath || !{value}.HasEmbeddedFile",
            "font" =>
                $"!{value}.HasFontName || !{value}.HasSize || {value}.Size > byte.MaxValue || {value}.Color is null || !{value}.Color.HasRed || {value}.Color.Red > byte.MaxValue || !{value}.Color.HasGreen || {value}.Color.Green > byte.MaxValue || !{value}.Color.HasBlue || {value}.Color.Blue > byte.MaxValue",
            "angular_unit" or "distance_unit" or "temperature_unit" =>
                $"{value} == 0 || !Enum.IsDefined({value})",
            "point_name" => MissingPointNameComponents(value),
            "vector" => $"!{value}.HasX || !{value}.HasY || !{value}.HasZ",
            "tolerance_vector_options" => string.Join(" || ", ToleranceNames.Select(name =>
                $"{value}.{name} is null || !{value}.{name}.HasEnabled || !{value}.{name}.HasValue")),
            "collection_instrument_id" =>
                $"!{value}.HasCollectionName || !{value}.HasInstrumentId",
            "collection_machine_id" =>
                $"!{value}.HasCollectionName || !{value}.HasMachineId",
            "collection_item_name" => MissingCollectionItemNameComponents(value),
            "collection_object_name" => MissingCollectionObjectNameComponents(value),
            "collection_vector_group_name" =>
                $"!{value}.HasCollectionName || !{value}.HasVectorGroupName",
            "collection_instrument_id_list" =>
                $"{value}.Values.Any(item => !item.HasCollectionName || !item.HasInstrumentId)",
            "collection_group_name_list" =>
                $"{value}.Values.Any(item => !item.HasCollectionName || !item.HasGroupName)",
            "collection_item_name_list" =>
                $"{value}.Values.Any(item => {MissingCollectionItemNameComponents("item")})",
            "collection_object_name_list" =>
                $"{value}.Values.Any(item => {MissingCollectionObjectNameComponents("item")})",
            "collection_vector_group_name_list" =>
                $"{value}.Values.Any(item => !item.HasCollectionName || !item.HasVectorGroupName)",
            "point_name_list" =>
                $"{value}.Values.Any(item => {MissingPointNameComponents("item")})",
            "vector_name_list" =>
                $"{value}.Values.Any(item => !item.HasCollectionName || !item.HasGroupName || !item.HasName)",
            _ => SpecializedValueMappings.ValidationCondition(input.SemanticType, value)
        };
        builder.Append(indentation).Append("if (").Append(condition).AppendLine(")");
        builder.Append(indentation).AppendLine("{");
        builder.Append(indentation).Append("    throw new ArgumentException(\"Request field '")
            .Append(EscapeCSharp(input.ArgumentId))
            .AppendLine("' must contain every exact-target component.\", nameof(request));");
        builder.Append(indentation).AppendLine("}");
    }

    private static string MissingPointNameComponents(string value) =>
        $"!{value}.HasCollectionName || !{value}.HasGroupName || !{value}.HasTargetName";

    private static string MissingCollectionItemNameComponents(string value) =>
        $"!{value}.HasCollectionName || !{value}.HasItemName || !{value}.HasItemType || {value}.ItemType == TargetProtocol.ItemType.Unspecified || !Enum.IsDefined({value}.ItemType)";

    private static string MissingCollectionObjectNameComponents(string value) =>
        $"!{value}.HasCollectionName || !{value}.HasObjectName || !{value}.HasObjectType || {value}.ObjectType == TargetProtocol.ObjectType.Unspecified || !Enum.IsDefined({value}.ObjectType)";
