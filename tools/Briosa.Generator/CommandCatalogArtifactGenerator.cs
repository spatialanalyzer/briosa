        {
            "logical" => prefix + $"BooleanValue: {valueExpression})",
            "whole_number" => prefix + $"IntegerValue: {valueExpression})",
            "floating_point" => prefix + $"DoubleValue: {valueExpression})",
            "string" or
            "chart_name" or
            "cloud_name" or
            "collection_name" or
            "frame_name" or
